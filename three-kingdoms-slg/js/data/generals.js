export const MAX_GENERAL_LEVEL = 50;

/**
 * 计算升到下一级所需经验
 * 经典公式：基础 100 * level * 1.5
 */
export function getExpRequiredForLevel(level) {
  if (level >= MAX_GENERAL_LEVEL) return 0;
  return Math.round(150 * Math.pow(level, 1.25));
}

/**
 * 为武将增加经验并处理升级
 * @param {Object} hero 武将对象
 * @param {number} expGain 获得经验值
 * @returns {Object} { leveledUp: boolean, oldLevel, newLevel, expGain }
 */
export function addGeneralExp(hero, expGain) {
  if (!hero.level) hero.level = 1;
  if (hero.exp === undefined || hero.exp === null) hero.exp = 0;

  const oldLevel = hero.level;
  if (hero.level >= MAX_GENERAL_LEVEL) {
    return { leveledUp: false, oldLevel, newLevel: oldLevel, expGain: 0 };
  }

  hero.exp += expGain;
  let leveledUp = false;

  while (hero.level < MAX_GENERAL_LEVEL) {
    const required = getExpRequiredForLevel(hero.level);
    if (hero.exp >= required) {
      hero.exp -= required;
      hero.level += 1;
      leveledUp = true;
      // 升级提升兵力上限 (每级+100基础带兵量)
      if (hero.maxSoldiers) {
        hero.maxSoldiers += 100;
        hero.currentSoldiers = (hero.currentSoldiers || 0) + 100;
      }
    } else {
      break;
    }
  }

  if (hero.level >= MAX_GENERAL_LEVEL) {
    hero.exp = 0;
  }

  return {
    leveledUp,
    oldLevel,
    newLevel: hero.level,
    expGain
  };
}
